"""
==============================================================================
Summary - Encapsulation, Inheritance, এবং Polymorphism
==============================================================================
এই ফাইলে অবজেক্ট ওরিয়েন্টেড প্রোগ্রামিং (OOP)-এর তিনটি গুরুত্বপূর্ণ স্তম্ভ 
এনক্যাপসুলেশন, ইনহেরিট্যান্স এবং পলিমরফিজম নিয়ে খুব সহজে বাংলায় আলোচনা করা হলো।

১. Encapsulation (এনক্যাপসুলেশন): 
ডেটা (ভ্যারিয়েবল) এবং মেথডকে একটি ক্লাসের মধ্যে একসাথে বেঁধে রাখা এবং বাইরের 
অ্যাক্সেস থেকে ডেটাকে সুরক্ষিত রাখাই হলো এনক্যাপসুলেশন। 
কেন দরকার: ডেটা হাইড (Data Hiding) করার জন্য। প্রাইভেট (__) এবং প্রটেক্টেড (_) 
ভ্যারিয়েবল ব্যবহার করে এটি করা হয়।

২. Inheritance (ইনহেরিট্যান্স): 
একটি ক্লাস (Child) যখন অন্য একটি ক্লাসের (Parent) বৈশিষ্ট্য (property/method) 
গ্রহণ করে, তখন তাকে ইনহেরিট্যান্স বলে।
কেন দরকার: একই কোড বারবার না লিখে কোড রিইউজ (Code Reusability) করার জন্য। 

৩. Polymorphism (পলিমরফিজম): 
'পলি' মানে বহু এবং 'মরফ' মানে রূপ। অর্থাৎ, একই জিনিসের বিভিন্ন রূপ। 
একই নামের মেথড বা ফাংশন যখন বিভিন্ন জায়গায় বিভিন্নভাবে কাজ করে, তাকে পলিমরফিজম বলে।
কেন দরকার: ফ্লেক্সিবিলিটি বাড়ানোর জন্য (যেমন মেথড ওভাররাইডিং, ডাক টাইপিং)।
"""

# ==============================================================================
# ১. Encapsulation (এনক্যাপসুলেশন) এর উদাহরণ
# ==============================================================================
class BankAccount:
    def __init__(self, owner, balance):
        self.owner = owner          # Public Attribute (সবাই দেখতে পাবে)
        self._bank_name = "City Bank" # Protected Attribute (সাবক্লাস দেখতে পাবে)
        self.__balance = balance    # Private Attribute (বাইরে থেকে দেখা যাবে না)

    # প্রাইভেট ডেটা অ্যাক্সেস বা আপডেট করার জন্য মেথড (Getter/Setter) ব্যবহার করা হয়
    def get_balance(self):
        return self.__balance

    def deposit(self, amount):
        if amount > 0:
            self.__balance += amount
            print(f"{amount} টাকা জমা হয়েছে। বর্তমান ব্যালেন্স: {self.__balance}")


# ==============================================================================
# ২. Inheritance (ইনহেরিট্যান্স) এর উদাহরণ
# ==============================================================================
# Parent Class (প্যারেন্ট ক্লাস)
class Animal:
    def __init__(self, name):
        self.name = name

    def eat(self):
        print(f"{self.name} খাবার খাচ্ছে...")

# Child Class (চাইল্ড ক্লাস) - এটি Animal ক্লাসকে ইনহেরিট করেছে
class Tiger(Animal):
    def hunt(self):
        print(f"{self.name} শিকার করছে!")

class Cow(Animal):
    def give_milk(self):
        print(f"{self.name} দুধ দিচ্ছে!")


# ==============================================================================
# ৩. Polymorphism (পলিমরফিজম) এর উদাহরণ
# ==============================================================================
# একই নামের মেথড (যেমন- sound), কিন্তু ক্লাস অনুযায়ী কাজ আলাদা।

class Bird:
    def sound(self):
        print("পাখি ডাকে: কিচির মিচির")

class Duck:
    def sound(self):
        print("হাঁস ডাকে: প্যাক প্যাক")

# পলিমরফিজম টেস্ট করার জন্য একটি সাধারণ ফাংশন
def make_animal_sound(animal_obj):
    animal_obj.sound() # অবজেক্ট অনুযায়ী তার নিজের sound() মেথড কল হবে


# ==============================================================================
# টেস্ট করার জন্য নিচের কোডগুলো রান করুন:
# ==============================================================================
if __name__ == "__main__":
    print("\n--- Encapsulation Test ---")
    account = BankAccount("Rahim", 1000)
    print("অ্যাকাউন্টের মালিক:", account.owner)
    # print(account.__balance) # এটি এরর দিবে, কারণ __balance প্রাইভেট!
    print("ব্যালেন্স (Getter এর মাধ্যমে):", account.get_balance())
    account.deposit(500)

    print("\n--- Inheritance Test ---")
    t = Tiger("রয়েল বেঙ্গল টাইগার")
    t.eat()   # Parent থেকে পেয়েছে
    t.hunt()  # নিজের মেথড

    c = Cow("সিন্ধি গরু")
    c.eat()       # Parent থেকে পেয়েছে
    c.give_milk() # নিজের মেথড

    print("\n--- Polymorphism Test ---")
    b = Bird()
    d = Duck()
    
    # একই ফাংশন, কিন্তু অবজেক্ট ভিন্ন হওয়ায় আউটপুট ভিন্ন (এটাই পলিমরফিজম)
    make_animal_sound(b)
    make_animal_sound(d)
