# ==============================================================================
if __name__ == "__main__":
    print("\n--- Decorator Test ---")
    say_hello()

    print("\n--- Instance Method Test ---")
    s1 = Student("Rahim", 20)
    s1.show_info() 

    print("\n--- Class Method Test ---")
    Student.change_school_name("XYZ Ideal School")
    s2 = Student("Karim", 22)
    s2.show_info() # নতুন স্কুলের নাম দেখাবে

    print("\n--- Static Method Test ---")
    Student.check_age(20)

    print("\n--- Property Decorator Test ---")
    emp = Employee("Hasan", 50000)
    print(f"বর্তমান বেতন: {emp.salary}") # Getter কল হবে
    emp.salary = 60000 # Setter কল হবে
    print(f"আপডেট বেতন: {emp.salary}")
