"""
==============================================================================
Decorator 9 - Summary (ডেকরেটর, ক্লাস মেথড, স্ট্যাটিক মেথড এবং প্রোপার্টি এর সামারি)
==============================================================================
এই ফাইলে আগের সবগুলো ডেকরেটর ক্লাসের (যেমন- Decorator 1 থেকে 8) মূল বিষয়গুলোর 
সারাংশ সহজ বাংলায় কোড সহ আলোচনা করা হলো।


১. Decorator (ডেকরেটর): ডেকরেটর হলো এমন একটি ফাংশন যা অন্য একটি ফাংশন বা ক্লাসের ক্ষমতা বা বৈশিষ্ট্য (behavior) পরিবর্তন বা বৃদ্ধি করতে পারে, কিন্তু মূল ফাংশনের কোড পরিবর্তন না করে। কেন দরকার: বারবার একই কোড না লিখে লগিং (logging), অথেনটিকেশন (authentication), বা কোনো ফাংশন কতক্ষণ সময় নিচ্ছে (execution time) তা চেক করার মতো কাজগুলো সহজে করার জন্য ডেকরেটর ব্যবহার করা হয়।

২. Instance Method (ইন্সট্যান্স মেথড): ক্লাস তৈরি করার পর এর ভেতরে যে সাধারণ মেথডগুলো আমরা লিখি (যেগুলোর প্রথম প্যারামিটার self থাকে), সেগুলোই ইন্সট্যান্স মেথড। কেন দরকার: ক্লাসের কোনো নির্দিষ্ট অবজেক্ট (instance) এর নিজস্ব ডেটা নিয়ে কাজ করতে এটি ব্যবহৃত হয়। যেমন- একজন নির্দিষ্ট স্টুডেন্ট এর নাম বা বয়স দেখতে চাইলে।

৩. Class Method (ক্লাস মেথড): ক্লাস মেথড কোনো নির্দিষ্ট অবজেক্টের সাথে যুক্ত থাকে না, এটি সরাসরি ক্লাসের সাথে যুক্ত থাকে। এর প্রথম প্যারামিটার হয় cls (self নয়)। এটি বানানোর জন্য @classmethod ডেকরেটর ব্যবহার করতে হয়। কেন দরকার: যখন ক্লাসের নিজস্ব ভ্যারিয়েবল (Class Variable) পরিবর্তন করার দরকার হয় বা ক্লাসের পুরো প্রপার্টি নিয়ে কাজ করতে হয়, তখন এটি লাগে।

৪. Static Method (স্ট্যাটিক মেথড): এটি ক্লাসের ভেতর থাকা সাধারণ একটি ফাংশনের মতোই কাজ করে। এর সাথে ক্লাস বা অবজেক্টের সরাসরি কোনো সম্পর্ক নেই। এর কোনো self বা cls প্যারামিটার থাকে না। এটি বানাতে @staticmethod ডেকরেটর লাগে। কেন দরকার: হেল্পার (helper) বা ইউটিলিটি কাজের জন্য (যেমন - কোনো ডেটা ভ্যালিডেট করা বা ফর্মুলা ক্যালকুলেট করা) এটি ব্যবহার হয়, যা ক্লাসের নিজস্ব ডেটা পরিবর্তন করে না।
"""

# ==============================================================================
# ১. Decorator (ডেকরেটর)
# ==============================================================================
# ডেকরেটর হলো এমন একটি ফাংশন যা অন্য একটি ফাংশনের ক্ষমতা (behavior) বাড়াতে সাহায্য করে।
# মূল ফাংশনের কোড পরিবর্তন না করেই নতুন ফিচার যোগ করতে এটি ব্যবহার করা হয়।

def my_decorator(func):
    def wrapper():
        print("--- ফাংশন কল হওয়ার আগে কিছু কাজ হচ্ছে ---")
        func()
        print("--- ফাংশন কল হওয়ার পরে কিছু কাজ হচ্ছে ---")
    return wrapper

@my_decorator
def say_hello():
    print("Hello! (হ্যালো!)")

# say_hello() কল করলে এটি my_decorator এর মাধ্যমে মডিফাই হয়ে আউটপুট দিবে।


# ==============================================================================
# ২. Instance, Class এবং Static Method এর ব্যবহার
# ==============================================================================
class Student:
    # Class Variable (এটি সব অবজেক্টের জন্য সেম থাকে)
    school_name = "ABC High School" 

    def __init__(self, name, age):
        self.name = name  # Instance Variable
        self.age = age    # Instance Variable

    # --------------------------------------------------------------------------
    # Instance Method (ইন্সট্যান্স মেথড)
    # --------------------------------------------------------------------------
    # প্রথম প্যারামিটার হিসেবে 'self' থাকে। এটি অবজেক্টের নিজস্ব ডেটা নিয়ে কাজ করে।
    def show_info(self):
        print(f"নাম: {self.name}, বয়স: {self.age}, স্কুল: {self.school_name}")

    # --------------------------------------------------------------------------
    # Class Method (ক্লাস মেথড)
    # --------------------------------------------------------------------------
    # প্রথম প্যারামিটার হিসেবে 'cls' থাকে। ক্লাসের নিজস্ব ভ্যারিয়েবল মডিফাই করতে এটি লাগে।
    # এটি বানাতে @classmethod ডেকরেটর ব্যবহার করতে হয়।
    @classmethod
    def change_school_name(cls, new_name):
        cls.school_name = new_name
        print(f"স্কুলের নতুন নাম আপডেট করা হলো: {cls.school_name}")
    
    # --------------------------------------------------------------------------
    # Static Method (স্ট্যাটিক মেথড)
    # --------------------------------------------------------------------------
    # এতে 'self' বা 'cls' কিছুই পাস করতে হয় না। এটি ক্লাসের ডেটা পরিবর্তন করে না।
    # হেল্পার/ইউটিলিটি কাজের জন্য এটি ব্যবহৃত হয়। @staticmethod ডেকরেটর লাগে।
    @staticmethod
    def check_age(age):
        if age >= 18:
            print("বয়স ১৮ বা তার বেশি, অ্যাডাল্ট।")
        else:
            print("বয়স ১৮ এর নিচে, মাইনর।")


# ==============================================================================
# ৩. Property Decorator (প্রোপার্টি ডেকরেটর - Getter ও Setter)
# ==============================================================================
# প্রাইভেট ভ্যারিয়েবল (যেমন: __salary) অ্যাক্সেস বা মডিফাই করার জন্য প্রোপার্টি ডেকরেটর লাগে।
class Employee:
    def __init__(self, name, salary):
        self.name = name
        self.__salary = salary # প্রাইভেট ভ্যারিয়েবল

    # Getter: ভ্যালু রিড (read) করার জন্য
    @property
    def salary(self):
        return self.__salary

    # Setter: ভ্যালু আপডেট বা সেট করার জন্য ভ্যালিডেশন সহ
    @salary.setter
    def salary(self, new_salary):
        if new_salary > 0:
            self.__salary = new_salary
        else:
            print("বেতন শূন্য বা তার কম হতে পারে না!")


