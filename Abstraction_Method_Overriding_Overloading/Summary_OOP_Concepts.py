# ==============================================================================
# ১. Abstraction (অ্যাবস্ট্রাকশন)
# ==============================================================================
# অ্যাবস্ট্রাকশন মানে হলো ভিতরের জটিল লজিক (implementation) লুকিয়ে রাখা এবং 
# শুধুমাত্র দরকারি জিনিস (functionality) ইউজারকে দেখানো। 
# পাইথনে 'abc' (Abstract Base Classes) মডিউল দিয়ে এটি করা হয়। 
# অ্যাবস্ট্রাক্ট ক্লাসের কোনো সরাসরি অবজেক্ট তৈরি করা যায় না।

from abc import ABC, abstractmethod

# এটি একটি অ্যাবস্ট্রাক্ট ক্লাস
class Animal(ABC):
    @abstractmethod
    def make_sound(self):
        pass  # এখানে কোনো কোড থাকবে না, চাইল্ড ক্লাস এটি ডিফাইন করবে

# চাইল্ড ক্লাস (অবশ্যই অ্যাবস্ট্রাক্ট মেথডটিকে ইমপ্লিমেন্ট করতে হবে)
class Dog(Animal):
    def make_sound(self):
        print("কুকুর ডাকে: ঘেউ ঘেউ")

class Cat(Animal):
    def make_sound(self):
        print("বিড়াল ডাকে: মিউ মিউ")

# a = Animal() # এটি এরর দিবে, কারণ অ্যাবস্ট্রাক্ট ক্লাসের অবজেক্ট হয় না।


# ==============================================================================
# ২. Method Overriding (মেথড ওভাররাইডিং)
# ==============================================================================
# যখন প্যারেন্ট ক্লাস (Parent Class) এবং চাইল্ড ক্লাসে (Child Class) একই নামের 
# মেথড থাকে, কিন্তু চাইল্ড ক্লাস নিজের মতো করে মেথডটির কাজ পরিবর্তন করে নেয়, 
# তখন তাকে মেথড ওভাররাইডিং বলে। 
# এটি Inheritance (ইনহেরিট্যান্স) এর ক্ষেত্রে কাজ করে।

class Vehicle:
    def start(self):
        print("যানবাহনটি স্টার্ট হচ্ছে...")

class Car(Vehicle):
    # প্যারেন্ট ক্লাসের start মেথডকে ওভাররাইড করা হলো
    def start(self):
        print("গাড়িটি চাবি দিয়ে স্টার্ট হচ্ছে...")

class Bike(Vehicle):
    # প্যারেন্ট ক্লাসের start মেথডকে ওভাররাইড করা হলো
    def start(self):
        print("বাইকটি কিক দিয়ে স্টার্ট হচ্ছে...")


# ==============================================================================
# ৩. Method Overloading (মেথড ওভারলোডিং)
# ==============================================================================
# একই ক্লাসে একই নামের একাধিক মেথড, কিন্তু তাদের প্যারামিটার আলাদা হলে তাকে 
# মেথড ওভারলোডিং বলে। 
# পাইথন ডিফল্টভাবে মেথড ওভারলোডিং সাপোর্ট করে না। তবে আমরা ডিফল্ট ভ্যালু (None) 
# বা *args ব্যবহার করে একই কাজ করতে পারি।

class Calculator:
    # এখানে a, b, c প্যারামিটার নিয়ে ট্রিক করা হয়েছে
    def add(self, a=None, b=None, c=None):
        if a != None and b != None and c != None:
            return a + b + c
        elif a != None and b != None:
            return a + b
        else:
            return "কমপক্ষে দুটি সংখ্যা দিন"

# ==============================================================================
# টেস্ট করার জন্য নিচের কোডগুলো রান করুন:
# ==============================================================================
if __name__ == "__main__":
    print("\n--- Abstraction Test ---")
    d = Dog()
    d.make_sound()
    c = Cat()
    c.make_sound()

    print("\n--- Method Overriding Test ---")
    my_car = Car()
    my_car.start()  # Car ক্লাসের নিজস্ব মেথড কল হবে
    my_bike = Bike()
    my_bike.start() # Bike ক্লাসের নিজস্ব মেথড কল হবে

    print("\n--- Method Overloading Test ---")
    calc = Calculator()
    print("দুটি সংখ্যার যোগফল:", calc.add(10, 20))
    print("তিনটি সংখ্যার যোগফল:", calc.add(10, 20, 30))
